/** Матрица кода: сторона и «тёмный ли модуль». */
export interface QrMatrix {
  size: number
  get: (row: number, col: number) => boolean
}

const isFinder = (n: number, r: number, c: number) => (r < 7 && c < 7) || (r < 7 && c >= n - 7) || (r >= n - 7 && c < 7)

/** Под плиткой со знаком — модули не рисуем (с запасом в полмодуля). */
export function underLogo(n: number, r: number, c: number): boolean {
  const cs = n * QR_LOGO_SHARE
  const c0 = (n - cs) / 2
  return c >= c0 - 0.6 && c <= c0 + cs + 0.6 && r >= c0 - 0.6 && r <= c0 + cs + 0.6
}

export function qrSvg(m: QrMatrix, style: QrStyle = 'iris'): string {
  const n = m.size
  const P = QR_QUIET
  const [a, b, c] = STOPS[style]
  const dots: string[] = []
  for (let r = 0; r < n; r++) {
    for (let col = 0; col < n; col++) {
      if (m.get(r, col) && !isFinder(n, r, col) && !underLogo(n, r, col)) {
        dots.push(`<rect x="${(col + 0.08).toFixed(2)}" y="${(r + 0.08).toFixed(2)}" width=".84" height=".84" rx=".3"/>`)
      }
    }
  }
  const eye = (x: number, y: number) => `<rect x="${x + 0.5}" y="${y + 0.5}" width="6" height="6" rx="1.8" fill="none" stroke="url(#g)" stroke-width="1"/>`
    + `<rect x="${x + 2}" y="${y + 2}" width="3" height="3" rx="1" fill="url(#g)"/>`
  const cs = n * QR_LOGO_SHARE
  const c0 = (n - cs) / 2
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-P} ${-P} ${n + 2 * P} ${n + 2 * P}" shape-rendering="geometricPrecision">`
    + `<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a}"/><stop offset=".55" stop-color="${b}"/><stop offset="1" stop-color="${c}"/></linearGradient></defs>`
    + `<rect x="${-P}" y="${-P}" width="${n + 2 * P}" height="${n + 2 * P}" rx="3" fill="#fff"/>`
    + `<g fill="url(#g)">${dots.join('')}</g>${eye(0, 0)}${eye(n - 7, 0)}${eye(0, n - 7)}`
    + `<rect x="${(c0 - 0.3).toFixed(2)}" y="${(c0 - 0.3).toFixed(2)}" width="${(cs + 0.6).toFixed(2)}" height="${(cs + 0.6).toFixed(2)}" rx="${(cs * 0.28).toFixed(2)}" fill="url(#g)"/>`
    + `<g transform="translate(${(c0 + cs * 0.1).toFixed(2)} ${(c0 + cs * 0.1).toFixed(2)}) scale(${(cs * 0.8 / 24).toFixed(4)})"><path d="${CORNFLOWER}" fill="#fff"/></g></svg>`
}

/** Стиль из запроса: `?style=bw` — чёрно-белый, иначе перелив. */
export function qrStyleOf(raw: unknown): QrStyle {
  return raw === 'bw' ? 'bw' : 'iris'
}
