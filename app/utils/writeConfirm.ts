// Вопросы перед записью в счёт — чистая функция, чтобы текст и число вопросов проверял тест.
// «Добавить» спрашивает дважды, как Windows перед необратимым шагом (просьба владельца
// 2026-09-28): повторное добавление задваивает товары, а отменить его можно только руками.

import type { WriteMode } from './writeOutcome'

/** «строку», «строки», «строк» — по числу. */
export function rowsWord(n: number): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return 'строку'
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'строки'
  return 'строк'
}

/**
 * Вопросы по порядку; пустой список — спрашивать нечего. «Заменить» спрашивает, только если в счёте
 * уже есть позиции (их заменят). «Добавить» — всегда дважды: сначала что и куда, потом «точно?» с
 * объяснением, чем грозит повтор.
 */
export function writeConfirmations(mode: WriteMode, existing: number, planned: number): string[] {
  if (mode === 'replace') {
    return existing > 0 ? [`В счёте уже ${existing} поз. Заменить их строками из задач?`] : []
  }
  const what = `${planned} ${rowsWord(planned)}`
  return [
    existing > 0
      ? `Добавить ${what} к ${existing} поз. счёта? Строки встанут после существующих.`
      : `Добавить ${what} в счёт?`,
    'Точно добавить? Если эти строки уже добавляли, в счёте будут дубли — отменить добавление нельзя, '
    + 'лишние позиции придётся удалять в карточке счёта.'
  ]
}
